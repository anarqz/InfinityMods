#!/usr/bin/env python3
"""Writes src/er_unicode_tables.h: the Unicode tables the HUD text cleaner needs, from Python's unicodedata.

  python3 -I mods/easyradio/gen_unicode.py

The C cleaner (er_text.c) reproduces the Python prototype's cleaner (hud_names),
so its tables come from the same Python rules:
  fold   code point -> ASCII text: NFKD, combining marks dropped, curly quotes -> "'", only printable ASCII
         without < > " kept (ascii_text, one character at a time; the ordinals U+00BA/U+00AA fold to nothing);
  word   ranges of re's \\w for str (isalnum() or '_');
  space  str.isspace() (also re's \\s for str);
  lower  str.lower() where it differs.
Only Unicode data, no game data. Re-run after a Python upgrade if the Unicode version matters.
"""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent / "src" / "er_unicode_tables.h"
RANGE = [cp for cp in range(0x110000) if not 0xD800 <= cp < 0xE000]


def fold(c):
    if c in "ºª":
        return ""
    text = unicodedata.normalize("NFKD", c)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = text.replace("’", "'").replace("‘", "'").replace("“", "'").replace("”", "'").replace('"', "'")
    return "".join(ch for ch in text if " " <= ch <= "~" and ch not in "<>")


def ranges(predicate):
    out, start = [], None
    for cp in range(0x110001):
        inside = cp < 0x110000 and not 0xD800 <= cp < 0xE000 and predicate(chr(cp))
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def table(name, mapping):
    """sorted (cp, offset, length) plus a pool of code points (lower) or bytes (fold)."""
    keys, pool, rows = sorted(mapping), [], []
    for cp in keys:
        rows.append(f"{{0x{cp:x},{len(pool)},{len(mapping[cp])}}}")
        pool += mapping[cp]
    return keys, pool, rows


def main():
    folds = {}
    for cp in RANGE:
        if cp < 0x80:
            continue
        text = fold(chr(cp))
        if text:
            folds[cp] = [ord(ch) for ch in text]
    lowers = {}
    for cp in RANGE:
        low = chr(cp).lower()
        if low != chr(cp):
            lowers[cp] = [ord(ch) for ch in low]
    words = ranges(lambda c: c.isalnum() or c == "_")
    spaces = [cp for cp in RANGE if chr(cp).isspace()]
    lines = [f"/* Generated by gen_unicode.py from Python {sys.version.split()[0]} unicodedata {unicodedata.unidata_version}. Do not edit. */",
             "#pragma once", "#include <stdint.h>",
             "typedef struct { uint32_t cp; uint32_t offset; uint8_t length; } ErMapRow;",
             "typedef struct { uint32_t first, last; } ErRange;"]
    for name, mapping, kind in (("fold", folds, "uint8_t"), ("lower", lowers, "uint32_t")):
        keys, pool, rows = table(name, mapping)
        lines.append(f"static const ErMapRow er_{name}_rows[{len(rows)}] = {{")
        lines += ["    " + ",".join(rows[i:i + 6]) + "," for i in range(0, len(rows), 6)]
        lines.append("};")
        lines.append(f"static const {kind} er_{name}_pool[{len(pool)}] = {{")
        lines += ["    " + ",".join(str(v) for v in pool[i:i + 24]) + "," for i in range(0, len(pool), 24)]
        lines.append("};")
    lines.append(f"static const ErRange er_word_ranges[{len(words)}] = {{")
    lines += ["    " + ",".join(f"{{0x{a:x},0x{b:x}}}" for a, b in words[i:i + 6]) + "," for i in range(0, len(words), 6)]
    lines.append("};")
    lines.append(f"static const uint32_t er_space_points[{len(spaces)}] = {{" + ",".join(f"0x{cp:x}" for cp in spaces) + "};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{OUT}: fold {len(folds)}, lower {len(lowers)}, word ranges {len(words)}, spaces {len(spaces)}")


if __name__ == "__main__":
    main()

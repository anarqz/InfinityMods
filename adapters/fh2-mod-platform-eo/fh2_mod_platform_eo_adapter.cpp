// azimuth_dir is the mod's own folder (<Azimuth>\mods\<game folder>\<mod> since ExtraOptions 0.6.0, the parent of plugins\,
// derived from the plugins path itself, so the depth does not matter): the paths the mod
// builds from it (its INI, its per-car files) stay inside that folder.
bool derive_mod_dir(const wchar_t* plugins) {
    size_t length = plugins ? std::wcslen(plugins) : 0;
    while (length && (plugins[length - 1] == L'\\' || plugins[length - 1] == L'/')) --length;
    size_t cut = length;
    while (cut && plugins[cut - 1] != L'\\' && plugins[cut - 1] != L'/') --cut;
    if (cut < 2 || _wcsnicmp(plugins + cut, L"plugins", length - cut) || length - cut != 7) return false;
    if (cut - 1 + 32 >= kPath) return false;
    wmemcpy(mod_dir, plugins, cut - 1);
    mod_dir[cut - 1] = 0;
    return swprintf_s(media_dir, kPath, L"%s\\plugins\\generated", mod_dir) > 0;
}

